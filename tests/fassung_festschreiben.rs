//! Gegentests für `scripts/Fassung-Festschreiben.ps1`: Version aus den
//! Conventional Commits seit dem letzten Tag, Zählregel des Changelogs und
//! das lokale Festschreiben (Merge chore(release) und leichter Tag). Jeder Fall
//! baut ein Wegwerf-Repo im Temp-Ordner ohne Remote; nichts geht hinaus.

use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::atomic::{AtomicUsize, Ordering};

use dashboard::dienst::programme::{self, Werkzeug};

const KOPF: &str = "\u{feff}CHANGELOG\n=========\n\nKopf.\n\n";
const ALT: &str = "0.3.4 - 2026-01-02\n------------------\n\nHinzugefügt\n- Alt.\n";
const LOCK: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"probe\"\nversion = \"0.3.4\"\n";

fn pwsh() -> Option<Command> {
    [Werkzeug::PowerShell7, Werkzeug::WindowsPowerShell].into_iter().find_map(|w| programme::befehl(w).ok())
}

fn bereit() -> bool {
    if pwsh().is_none() || programme::befehl(Werkzeug::Git).is_err() || programme::befehl(Werkzeug::Node).is_err() {
        return !dashboard::ueberspringen("PowerShell, git oder Node fehlen");
    }
    true
}

static ZAEHLER: AtomicUsize = AtomicUsize::new(0);

struct Ort(PathBuf);

impl Drop for Ort {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

impl Ort {
    /// Ein Repo auf main mit Tag v0.3.4 auf dem ersten Commit, Cargo.toml,
    /// Cargo.lock, web/package.json und web/package-lock.json in 0.3.4.
    fn neu() -> Ort {
        let n = ZAEHLER.fetch_add(1, Ordering::SeqCst);
        let o = Ort(std::env::temp_dir().join(format!("dashboard-fassung-{}-{n}", std::process::id())));
        let _ = std::fs::remove_dir_all(&o.0);
        std::fs::create_dir_all(&o.0).unwrap();
        o.git(&["init", "-q", "-b", "main"]);
        for (k, v) in [("core.autocrlf", "false"), ("user.name", "Ranke"), ("user.email", "ranke2@proton.me")] {
            o.git(&["config", k, v]);
        }
        o.datei("Cargo.toml", "[package]\nname = \"probe\"\nversion = \"0.3.4\"\nedition = \"2021\"\n\n[dependencies]\n");
        o.datei("src/lib.rs", "");
        o.datei("Cargo.lock", LOCK);
        o.datei(".gitignore", "/target\n");
        o.datei("web/package.json", "{\n\t\"name\": \"probe-web\",\n\t\"private\": true,\n\t\"version\": \"0.3.4\"\n}\n");
        o.datei(
            "web/package-lock.json",
            "{\n\t\"name\": \"probe-web\",\n\t\"version\": \"0.3.4\",\n\t\"lockfileVersion\": 3,\n\t\"requires\": true,\n\t\"packages\": {\n\t\t\"\": {\n\t\t\t\"name\": \"probe-web\",\n\t\t\t\"version\": \"0.3.4\"\n\t\t}\n\t}\n}\n",
        );
        o.changelog("");
        o.commit("chore(release): v0.3.4");
        o.git(&["tag", "v0.3.4"]);
        o
    }

    fn git(&self, args: &[&str]) -> String {
        let a = programme::befehl(Werkzeug::Git).unwrap().arg("-C").arg(&self.0).args(args).output().unwrap();
        assert!(a.status.success(), "git {args:?}: {}", String::from_utf8_lossy(&a.stderr));
        String::from_utf8_lossy(&a.stdout).trim().to_string()
    }

    fn datei(&self, pfad: &str, inhalt: &str) {
        let p = self.0.join(pfad);
        std::fs::create_dir_all(p.parent().unwrap()).unwrap();
        std::fs::write(p, inhalt).unwrap();
    }

    fn lesen(&self, pfad: &str) -> String {
        std::fs::read_to_string(self.0.join(pfad)).unwrap()
    }

    /// CHANGELOG.txt mit diesem Inhalt unter Unreleased.
    fn changelog(&self, unreleased: &str) {
        self.datei("CHANGELOG.txt", &format!("{KOPF}Unreleased\n----------\n\n{unreleased}\n{ALT}"));
    }

    fn commit(&self, betreff: &str) {
        self.git(&["add", "-A"]);
        self.git(&["commit", "-q", "--allow-empty", "-m", betreff]);
    }

    /// Mit -Pruefen, sonst wie aus Freigeben.ps1 mit -Basis main.
    fn lauf(&self, pruefen: bool) -> (i32, String) {
        self.lauf_mit(if pruefen { &["-Pruefen"] } else { &["-Basis", "main"] })
    }

    fn lauf_mit(&self, args: &[&str]) -> (i32, String) {
        let skript = Path::new(env!("CARGO_MANIFEST_DIR")).join("scripts").join("Fassung-Festschreiben.ps1");
        let mut c = pwsh().unwrap();
        c.args(["-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-File"]).arg(skript).arg("-Repo").arg(&self.0).args(args);
        let a = c.output().unwrap();
        (a.status.code().unwrap_or(-1), format!("{}{}", String::from_utf8_lossy(&a.stdout), String::from_utf8_lossy(&a.stderr)))
    }
}

/// Version: feat oder ! hebt die mittlere Zahl, alles andere die letzte; Pflege
/// braucht die eine Pflege-Zeile.
#[test]
fn version_aus_den_commits() {
    if !bereit() {
        return;
    }
    for (betreffe, unreleased, soll) in [
        (&["fix(web): a"][..], "Behoben\n- A.\n", "0.3.5"),
        (&["docs: a", "chore(merge): a nach main"][..], "Geändert\n- Pflege ohne sichtbare Änderung.\n", "0.3.5"),
        (&["perf: a"][..], "Geändert\n- Schneller.\n", "0.3.5"),
        (&["feat(api): a", "fix: b"][..], "Hinzugefügt\n- A.\n\nBehoben\n- B.\n", "0.4.0"),
        (&["refactor!: a"][..], "Geändert\n- Bruch: A fällt weg.\n", "0.4.0"),
        (&["revert!: a"][..], "Entfernt\n- Bruch: A wieder weg.\n", "0.4.0"),
    ] {
        let o = Ort::neu();
        o.changelog(unreleased);
        for b in betreffe {
            o.commit(b);
        }
        let (code, text) = o.lauf(true);
        assert_eq!(code, 0, "{betreffe:?}:\n{text}");
        assert!(text.contains(&format!("Nächste Fassung: {soll} ")), "{betreffe:?} soll {soll}:\n{text}");
        assert!(o.git(&["tag", "--list", "v0.4.0", "v0.3.5"]).is_empty(), "-Pruefen setzt keinen Tag");
    }
}

/// Zählregel: jeder Fall bricht mit dem auslösenden Commit im Satz ab.
#[test]
fn changelog_zaehlregel() {
    if !bereit() {
        return;
    }
    for (betreff, unreleased, muster) in [
        ("fix(web): Knopf geht", "Geändert\n- Etwas.\n", "fix ohne Zeile unter Behoben; ausgelöst von „fix(web): Knopf geht“"),
        ("feat: Neues Ding", "Behoben\n- Etwas.\n", "feat ohne Zeile unter Hinzugefügt oder Geändert; ausgelöst von „feat: Neues Ding“"),
        ("feat!: Alles anders", "Hinzugefügt\n- Etwas.\n", "Bruch ohne Zeile „- Bruch: …“ unter Geändert oder Entfernt; ausgelöst von „feat!: Alles anders“"),
        ("fix!: Weg damit", "Hinzugefügt\n- Bruch: steht falsch.\n\nBehoben\n- B.\n", "ausgelöst von „fix!: Weg damit“"),
        ("docs: nur Text", "", "Unreleased in CHANGELOG.txt ist leer"),
        ("feat: x", "Geändert\n- Pflege ohne sichtbare Änderung.\n", "sie zählt nur bei reiner Pflege (kein feat, fix, perf oder !), ausgelöst von „feat: x“"),
        (
            "perf: schneller",
            "Geändert\n- Pflege ohne sichtbare Änderung.\n",
            "sie zählt nur bei reiner Pflege (kein feat, fix, perf oder !), ausgelöst von „perf: schneller“",
        ),
        ("docs: x", "Hinzugefügt\n- Pflege ohne sichtbare Änderung.\n", "Unreleased in CHANGELOG.txt ist leer"),
    ] {
        let o = Ort::neu();
        o.changelog(unreleased);
        o.commit(betreff);
        let vorher = o.git(&["rev-parse", "HEAD"]);
        let (code, text) = o.lauf(false);
        assert_eq!(code, 1, "{betreff}:\n{text}");
        assert!(text.contains(muster), "{betreff}: erwartet „{muster}“:\n{text}");
        assert_eq!(o.git(&["rev-parse", "HEAD"]), vorher, "{betreff}: main bleibt");
        assert_eq!(o.git(&["branch", "--list", "freigabe/*"]), "", "{betreff}: kein Zweig");
    }
}

/// Vorbedingungen: nicht auf main, kein Commit seit dem Tag, Tag schon da, Zweig schon da, schmutziger Baum.
#[test]
fn vorbedingungen() {
    if !bereit() {
        return;
    }
    let o = Ort::neu();
    let (code, text) = o.lauf(true);
    assert_eq!((code, text.contains("keinen Commit")), (1, true), "{text}");
    o.changelog("Behoben\n- A.\n");
    o.commit("fix: a");
    o.git(&["branch", "freigabe/v0.3.5"]);
    let (code, text) = o.lauf(true);
    assert_eq!((code, text.contains("Der Zweig freigabe/v0.3.5 liegt schon da")), (1, true), "{text}");
    o.git(&["branch", "-D", "freigabe/v0.3.5"]);
    o.git(&["branch", "freigabe"]);
    let (code, text) = o.lauf(true);
    assert_eq!((code, text.contains("Der Zweig freigabe verhindert den Zweig freigabe/v0.3.5")), (1, true), "{text}");
    o.git(&["branch", "-D", "freigabe"]);
    o.git(&["checkout", "-q", "-b", "seite"]);
    o.git(&["tag", "v0.3.5"]);
    let (code, text) = o.lauf(true);
    assert_eq!((code, text.contains("nicht auf main")), (1, true), "{text}");
    o.git(&["checkout", "-q", "main"]);
    o.git(&["tag", "-d", "v0.3.5"]);
    o.git(&["checkout", "-q", "-b", "seite2", "v0.3.4"]);
    o.commit("chore: daneben");
    o.git(&["tag", "v0.3.5"]);
    o.git(&["checkout", "-q", "main"]);
    let (code, text) = o.lauf(true);
    assert_eq!((code, text.contains("Den Tag v0.3.5 gibt es schon")), (1, true), "{text}");
    o.git(&["tag", "-d", "v0.3.5"]);
    o.datei("src/lib.rs", "// offen\n");
    let (code, text) = o.lauf(false);
    assert_eq!((code, text.contains("nicht sauber")), (1, true), "{text}");
    assert_eq!(o.git(&["tag", "--list", "v0.3.5"]), "");
}

/// Allein aufgerufen (ohne -Basis, also ohne die Prüfungen von Freigeben.ps1) schreibt es nichts fest.
#[test]
fn festschreiben_nur_mit_basis() {
    if !bereit() {
        return;
    }
    let o = Ort::neu();
    o.changelog("Behoben\n- A.\n");
    o.commit("fix: a");
    let vorher = o.git(&["for-each-ref", "--format=%(refname) %(objectname)"]);
    let (code, text) = o.lauf_mit(&[]);
    assert_eq!(code, 1, "{text}");
    assert!(text.contains("Festgeschrieben wird nur aus scripts/Freigeben.ps1") && text.contains("Es wurde nichts geändert."), "{text}");
    assert_eq!(o.git(&["for-each-ref", "--format=%(refname) %(objectname)"]), vorher, "kein Merge, kein Tag, kein Zweig");
    assert_eq!(o.git(&["worktree", "list"]).lines().count(), 1);
}

/// Festschreiben: Release-Commit auf freigabe/v0.4.0, Merge auf main, leichter Tag, alle Versionen gleich.
#[test]
fn festschreiben_und_gegenprobe() {
    if !bereit() {
        return;
    }
    let o = Ort::neu();
    o.changelog("Hinzugefügt\n- Neu.\n");
    o.commit("feat(web): neu");
    let vorher = o.git(&["rev-parse", "HEAD"]);
    let (code, text) = o.lauf(false);
    assert_eq!(code, 0, "{text}");
    assert!(text.contains("Festgeschrieben: Fassung 0.4.0"), "{text}");
    let kopf = o.git(&["rev-parse", "HEAD"]);
    assert_eq!(o.git(&["rev-parse", "v0.4.0"]), kopf, "Tag auf dem Merge-Commit");
    assert_eq!(o.git(&["cat-file", "-t", "v0.4.0"]), "commit", "leichter Tag");
    assert_eq!(o.git(&["rev-parse", "HEAD^1"]), vorher, "erster Elternteil ist das alte main");
    assert_eq!(o.git(&["log", "-1", "--format=%s", "HEAD"]), "chore(release): v0.4.0");
    assert_eq!(o.git(&["log", "-1", "--format=%s", "HEAD^2"]), "chore(release): v0.4.0");
    assert_eq!(o.git(&["branch", "--list", "freigabe/*"]), "");
    assert_eq!(o.git(&["worktree", "list"]).lines().count(), 1);
    assert_eq!(o.git(&["status", "--porcelain"]), "");
    let geaendert = o.git(&["diff", "--name-only", "HEAD^1", "HEAD"]);
    assert_eq!(geaendert.lines().collect::<Vec<_>>(), ["CHANGELOG.txt", "Cargo.lock", "Cargo.toml", "web/package-lock.json", "web/package.json"]);
    assert!(o.lesen("Cargo.toml").contains("version = \"0.4.0\"\nedition"));
    assert!(o.lesen("Cargo.lock").contains("name = \"probe\"\nversion = \"0.4.0\""));
    let paket: serde_json::Value = serde_json::from_str(&o.lesen("web/package.json")).unwrap();
    let lock: serde_json::Value = serde_json::from_str(&o.lesen("web/package-lock.json")).unwrap();
    assert_eq!([&paket["version"], &lock["version"], &lock["packages"][""]["version"]], ["0.4.0", "0.4.0", "0.4.0"]);
    let cl = o.lesen("CHANGELOG.txt");
    assert!(cl.starts_with(KOPF), "Kopf und BOM bleiben");
    let rest = &cl[KOPF.len()..];
    let (titel, danach) = rest.strip_prefix("Unreleased\n----------\n\n").expect("neues leeres Unreleased oben").split_once('\n').unwrap();
    let datum = titel.strip_prefix("0.4.0 - ").expect(titel);
    assert!(chrono::NaiveDate::parse_from_str(datum, "%Y-%m-%d").is_ok() && datum.len() == 10, "{titel}");
    assert!(danach.starts_with("------------------\n\nHinzugefügt\n- Neu.\n\n0.3.4 - 2026-01-02"), "{danach}");

    // Gegenprobe: scheitert npm (kaputtes package.json), bleibt main, wie es war.
    let o = Ort::neu();
    o.changelog("Behoben\n- A.\n");
    o.datei("web/package.json", "{ kaputt");
    o.commit("fix: a");
    let vorher = o.git(&["rev-parse", "HEAD"]);
    let (code, text) = o.lauf(false);
    assert_eq!(code, 2, "{text}");
    assert!(text.contains("npm version 0.3.5") && text.contains("Zurückgenommen"), "{text}");
    assert_eq!(o.git(&["rev-parse", "HEAD"]), vorher);
    assert_eq!(o.git(&["tag", "--list", "v0.3.5"]), "");
    assert_eq!(o.git(&["branch", "--list", "freigabe/*"]), "");
    assert_eq!(o.git(&["worktree", "list"]).lines().count(), 1);
    assert_eq!(o.git(&["status", "--porcelain"]), "");
}

/// Bewegt sich main oder wechselt der gemeinsame Arbeitsbaum den Zweig, während
/// die Hooks des Release-Commits laufen, bekommt nichts den Merge oder den Tag.
#[test]
fn main_bewegt_sich_waehrend_des_festschreibens() {
    if !bereit() {
        return;
    }
    for (name, befehl) in [("main bewegt", "commit -q --allow-empty --no-verify -m 'chore: ungeprueft'"), ("Zweig gewechselt", "switch -q -c anderer-chat")] {
        let o = Ort::neu();
        o.changelog("Hinzugefügt\n- Neu.\n");
        o.commit("feat(web): neu");
        let vorher = o.git(&["rev-parse", "HEAD"]);
        // Der Hook läuft im vorübergehenden Worktree und greift wie ein anderer Chat in den gemeinsamen Baum.
        let repo = o.0.to_str().unwrap().replace('\\', "/");
        o.datei(".git/hooks/pre-commit", &format!("#!/bin/sh\nunset GIT_DIR GIT_INDEX_FILE GIT_WORK_TREE GIT_PREFIX\ngit -C '{repo}' {befehl}\n"));
        let (code, text) = o.lauf(false);
        assert_eq!(code, 1, "{name}:\n{text}");
        assert!(text.contains("hat sich main bewegt") && text.contains("Zurückgenommen"), "{name}:\n{text}");
        assert_eq!(o.git(&["tag", "--list", "v0.4.0"]), "", "{name}: kein Tag");
        assert_eq!(o.git(&["branch", "--list", "freigabe/*"]), "", "{name}: kein Zweig");
        assert_eq!(o.git(&["worktree", "list"]).lines().count(), 1, "{name}");
        // Kein Merge, weder auf main noch auf dem Zweig des anderen Chats.
        let main = if name == "main bewegt" { "main^" } else { "main" };
        assert_eq!(o.git(&["rev-parse", main]), vorher, "{name}");
        assert_eq!(o.git(&["rev-parse", "HEAD"]), o.git(&["rev-parse", if name == "main bewegt" { "main" } else { "anderer-chat" }]), "{name}");
        assert_eq!(o.git(&["rev-list", "--merges", "--count", "--all"]), "0", "{name}: kein Merge");
    }
}
